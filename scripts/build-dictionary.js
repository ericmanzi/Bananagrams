// Regenerates src/dictionary/enable.js from the ENABLE word list.
//
//   curl -o /tmp/enable1.txt https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
//   node scripts/build-dictionary.js /tmp/enable1.txt
//
// ENABLE (Enhanced North American Benchmark LExicon) is in the public domain,
// so it can ship inside the app. It is bundled rather than downloaded, so the
// game works offline and starts without a network round trip.

const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-dictionary.js <wordlist.txt>');
  process.exit(1);
}

const words = fs
  .readFileSync(src, 'utf8')
  .split('\n')
  .map((w) => w.trim().toUpperCase())
  .filter((w) => w.length >= 2 && /^[A-Z]+$/.test(w));

const out = path.join(__dirname, '..', 'src', 'dictionary', 'enable.js');
fs.writeFileSync(
  out,
  '// Generated by scripts/build-dictionary.js from the public-domain ENABLE list. Do not edit by hand.\n' +
    `module.exports = ${JSON.stringify(words.join('\n'))};\n`,
);
console.log(`Wrote ${words.length} words to ${path.relative(process.cwd(), out)}`);
