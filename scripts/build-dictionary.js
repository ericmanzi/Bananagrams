// Regenerates src/dictionary/sowpods.js from a SOWPODS word list.
//
//   curl -o /tmp/sowpods.txt https://raw.githubusercontent.com/jesstess/Scrabble/master/scrabble/sowpods.txt
//   node scripts/build-dictionary.js /tmp/sowpods.txt
//
// This is the same list the web game at ericmanzi.github.io/bananagrams fetches
// at runtime. The app bundles it instead, so it works offline and starts
// without a network round trip.

const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-dictionary.js <wordlist.txt>');
  process.exit(1);
}

const words = fs
  .readFileSync(src, 'utf8')
  .split('\n')
  .map((w) => w.trim().toUpperCase())
  .filter((w) => w.length >= 2 && /^[A-Z]+$/.test(w));

const out = path.join(__dirname, '..', 'src', 'dictionary', 'sowpods.js');
fs.writeFileSync(
  out,
  '// Generated by scripts/build-dictionary.js. Do not edit by hand.\n' +
    `module.exports = ${JSON.stringify(words.join('\n'))};\n`,
);
console.log(`Wrote ${words.length} words to ${path.relative(process.cwd(), out)}`);
